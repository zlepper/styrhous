// Shared paths and helpers for the Harbour design-oracle scripts.
import { readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const scriptDir = dirname(fileURLToPath(import.meta.url));
export const repoRoot = resolve(scriptDir, "..", "..");
export const harbourDir = join(repoRoot, "docs", "design-oracles", "harbour");
export const srcDir = join(harbourDir, "src");
export const fontsDir = join(harbourDir, "fonts");
export const manifestPath = join(harbourDir, "manifest.toml");
export const compareOutDir = join(repoRoot, "target", "design-oracles");
/** The static font files the egui app embeds (generated by instance-fonts.sh). */
export const appFontsDir = join(repoRoot, "crates", "components", "assets", "fonts");
/** The icon SVGs the egui app embeds (generated by extract-icons.mjs). */
export const appIconsDir = join(repoRoot, "crates", "components", "assets", "icons");

/**
 * Runs an entry point's `main` (sync or async) when `importMeta` belongs to the script Node was
 * started with, so tests can import the module's helpers without running it. A failure prints its
 * message and sets the exit code to `failureCode`.
 */
export function runMain(importMeta, main, { failureCode = 1 } = {}) {
  const entry = process.argv[1];
  if (!entry || realpathSync(entry) !== realpathSync(fileURLToPath(importMeta.url))) return;
  return Promise.resolve()
    .then(main)
    .catch((error) => {
      console.error(error.message);
      process.exitCode = failureCode;
    });
}

export const bricolageFamily = "Bricolage Grotesque";
const bricolageInstancePattern = /^BricolageGrotesque-Bold-opsz(\d+)\.ttf$/;

/** CSS family name of the static Bricolage Grotesque instance for one optical size. */
export function bricolageOpszFamily(opsz) {
  return `${bricolageFamily} opsz${opsz}`;
}

/** Optical sizes with a generated Bold Bricolage Grotesque instance, ascending. */
export function bricolageOpszSizes() {
  return readdirSync(join(appFontsDir, "bricolagegrotesque"))
    .map((name) => name.match(bricolageInstancePattern)?.[1])
    .filter(Boolean)
    .map(Number)
    .sort((a, b) => a - b);
}

/**
 * Last family in every Harbour stack before the generic: a DejaVu Sans subset holding exactly the
 * characters the boards use that a primary Harbour font lacks (instance-fonts.sh generates it and
 * its codepoint list).
 */
export const fallbackFamily = "Harbour Fallback";

/** The fallback subset's codepoints as a CSS unicode-range value ("" if no fallback is needed). */
export function fallbackUnicodeRange(fontsRoot = fontsDir) {
  return readFileSync(join(fontsRoot, "dejavu", "unicode-range.txt"), "utf8").trim();
}

/** The static families instance-fonts.sh writes as `<dir>/<prefix>-<Style>.ttf`, one per weight. */
const staticFamilies = [
  { family: "Figtree", dir: "figtree", prefix: "Figtree" },
  { family: "IBM Plex Mono", dir: "ibmplexmono", prefix: "IBMPlexMono" },
  { family: "IBM Plex Sans Condensed", dir: "ibmplexsanscondensed", prefix: "IBMPlexSansCondensed" },
];

/** OpenType style names of upright static instances and their usWeightClass. */
const styleWeights = {
  Thin: 100,
  ExtraLight: 200,
  Light: 300,
  Regular: 400,
  Medium: 500,
  SemiBold: 600,
  Bold: 700,
  ExtraBold: 800,
  Black: 900,
};

/** The faces of one static family found in the app's font directory, by ascending weight. */
function staticFamilyFaces({ family, dir, prefix }) {
  const pattern = new RegExp(`^${prefix}-(\\w+)\\.ttf$`);
  const faces = readdirSync(join(appFontsDir, dir))
    .map((name) => [name, name.match(pattern)?.[1]])
    .filter(([, style]) => style)
    .map(([name, style]) => {
      const weight = styleWeights[style];
      if (!weight) throw new Error(`${dir}/${name}: unknown style ${style}`);
      return { family, weight, path: join(appFontsDir, dir, name) };
    })
    .sort((a, b) => a.weight - b.weight);
  if (faces.length === 0) throw new Error(`no ${family} faces in ${appFontsDir}/${dir}; run instance-fonts.sh`);
  return faces;
}

/**
 * The @font-face set for the boards, pointing at exactly the files the app embeds so Chrome and
 * egui rasterize the same outlines. The faces are read from the font directory, which
 * instance-fonts.sh fills with the weights Google Fonts serves for the boards' request
 * (`Figtree:wght@400;500;600;700`, `IBM Plex Mono:wght@400;500`,
 * `IBM Plex Sans Condensed:wght@500;600`), so weight matching behaves the same, except that IBM
 * Plex Mono also gets its real SemiBold for the boards' weight-600 text instead of Chrome's
 * synthesized bold. Bricolage Grotesque (`opsz,wght@12..96,500;12..96,700`) is optically sized by
 * Chrome (opsz = font-size px); each static instance therefore gets its own family, and openBoard()
 * points every Bricolage element at the instance for its font size.
 */
export function fontFaces() {
  const unicodeRange = fallbackUnicodeRange();
  return [
    ...staticFamilies.flatMap(staticFamilyFaces),
    ...bricolageOpszSizes().map((opsz) => ({
      family: bricolageOpszFamily(opsz),
      weight: 700,
      path: join(appFontsDir, "bricolagegrotesque", `BricolageGrotesque-Bold-opsz${opsz}.ttf`),
    })),
    ...(unicodeRange
      ? [
          {
            // One face for every weight, so Chrome never synthesizes bold (egui cannot either).
            family: fallbackFamily,
            weight: "100 900",
            checkWeight: 400,
            unicodeRange,
            path: join(appFontsDir, "dejavu", "DejaVuSans-HarbourFallback.ttf"),
          },
        ]
      : []),
  ];
}

/**
 * (Re)writes fonts.css from fontFaces() into `dir` (default src/); every board links it. The font
 * URLs are relative to src/, where the file is served from.
 */
export function writeFontsCss(dir = srcDir) {
  const rules = fontFaces().map((face) => {
    const url = relative(srcDir, face.path).split("\\").join("/");
    const range = face.unicodeRange ? `\n  unicode-range: ${face.unicodeRange};` : "";
    return `@font-face {
  font-family: "${face.family}";
  font-style: normal;
  font-weight: ${face.weight};
  font-display: block;
  src: url("${url}") format("truetype");${range}
}`;
  });
  writeFileSync(
    join(dir, "fonts.css"),
    `/* Generated by scripts/design-oracles (lib.mjs writeFontsCss). Do not edit. */\n${rules.join("\n")}\n`,
  );
}

/** Board ID from a design file name: `A02-Pods.dc.html` -> `A02`, `Main.dc.html` -> `Main`. */
export function boardIdFromFileName(fileName) {
  return fileName.replace(/\.dc\.html$/, "").split("-")[0];
}

/** Reads the `<meta name="harbour-board">` block that `extract` writes into each board. */
export function readBoardMeta(id) {
  const html = readFileSync(join(srcDir, `${id}.html`), "utf8");
  const match = html.match(/<meta name="harbour-board" content='([^']*)'>/);
  if (!match) throw new Error(`${id}.html has no harbour-board meta; re-run extract`);
  return JSON.parse(match[1]);
}

/**
 * Whether a board is a hand-written calibration board (e.g. CAL) rather than a design artboard.
 * Calibration boards link the shared harbour.css, are kept by `extract` and render like any board.
 */
export function isCalibrationBoard(id) {
  return readBoardMeta(id).calibration === true;
}

/** All extracted board IDs in a stable, human-friendly order. */
export function listBoardIds() {
  return readdirSync(srcDir)
    .filter((name) => name.endsWith(".html"))
    .map((name) => name.slice(0, -".html".length))
    .sort(compareBoardIds);
}

const groupOrder = ["Main", "C", "A", "L", "Y"];

export function compareBoardIds(a, b) {
  const group = (id) => groupOrder.indexOf(id === "Main" ? "Main" : id[0]);
  return group(a) - group(b) || a.localeCompare(b, "en", { numeric: true });
}

/** Resolves CLI board IDs against the known set, failing on unknown ones. */
export function selectBoardIds(requested, known) {
  if (requested.length === 0) return known;
  const unknown = requested.filter((id) => !known.includes(id));
  if (unknown.length > 0) {
    throw new Error(`Unknown board ID(s): ${unknown.join(", ")}. Known: ${known.join(", ")}`);
  }
  return requested;
}

/** The extracted boards named on the command line, or all of them. */
export function boardIdsFromArgv(argv = process.argv.slice(2)) {
  return selectBoardIds(argv, listBoardIds());
}
